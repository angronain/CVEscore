#!/usr/bin/env python3
"""Deeper look at the test predictions than evaluate.py: significance, drift, errors, triage.

Usage:
    python scripts/analyze_results.py                 # compares deberta vs tfidf
    python scripts/analyze_results.py --model deberta --baseline tfidf

Reads:  data/processed/test.parquet, results/preds_{model,baseline}.parquet
Writes: results/analysis.md, results/analysis.json
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from baselines import METRICS, add_scores  # noqa: E402

SEVERITIES = ["None", "Low", "Medium", "High", "Critical"]


def bootstrap_diff(a: np.ndarray, b: np.ndarray, n: int = 1000, seed: int = 0) -> tuple[float, float, float]:
    """Paired bootstrap of mean(a) - mean(b): point estimate and 95% interval."""
    rng = np.random.default_rng(seed)
    d = a.astype(float) - b.astype(float)
    boots = np.array([d[rng.integers(0, len(d), len(d))].mean() for _ in range(n)])
    return float(d.mean()), float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))


def coverage_at(ok_sorted: np.ndarray, target: float) -> float:
    running = np.cumsum(ok_sorted) / np.arange(1, len(ok_sorted) + 1)
    hit = np.where(running >= target)[0]
    return float((hit.max() + 1) / len(ok_sorted)) if len(hit) else 0.0


def md(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    def f(v):
        if isinstance(v, (float, np.floating)):
            return floatfmt.format(v)
        return str(v)
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(f(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", type=Path, default=Path("data/processed"))
    p.add_argument("--results", type=Path, default=Path("results"))
    p.add_argument("--model", default="deberta")
    p.add_argument("--baseline", default="tfidf")
    args = p.parse_args()

    test = add_scores(pd.read_parquet(args.data / "test.parquet")).set_index("id")
    m = pd.read_parquet(args.results / f"preds_{args.model}.parquet").set_index("id").loc[test.index]
    b = pd.read_parquet(args.results / f"preds_{args.baseline}.parquet").set_index("id").loc[test.index]

    exact_m = (test[METRICS].values == m[METRICS].values).all(axis=1)
    exact_b = (test[METRICS].values == b[METRICS].values).all(axis=1)
    sev_m = test["severity"].values == m["severity"].values
    sev_b = test["severity"].values == b["severity"].values
    err_m = np.abs(test["score"].values - m["score"].values)
    err_b = np.abs(test["score"].values - b["score"].values)
    out, report = {}, [f"# CVEscore analysis: {args.model} vs {args.baseline}\n",
                       f"{len(test):,} test CVEs. Generated by `scripts/analyze_results.py`.\n"]

    # 1. Is the gain over the baseline real? Paired bootstrap on the same CVEs.
    sig = {
        "Exact vector": bootstrap_diff(exact_m, exact_b),
        "Severity acc.": bootstrap_diff(sev_m, sev_b),
        "Score MAE (lower is better)": bootstrap_diff(err_m, err_b),
        "Score within ±1.0": bootstrap_diff(err_m <= 1.0, err_b <= 1.0),
    }
    out["bootstrap"] = {k: dict(zip(["diff", "lo", "hi"], v)) for k, v in sig.items()}
    report += ["## 1. Gain over the baseline (paired bootstrap, 1,000 resamples)\n",
               md(pd.DataFrame([{"Metric": k, f"{args.model} − {args.baseline}": d, "95% CI low": lo,
                                 "95% CI high": hi} for k, (d, lo, hi) in sig.items()]), "{:+.4f}"), ""]

    within = {"Score within ±0.5": (err_m <= 0.5).mean(), "Score within ±1.0": (err_m <= 1.0).mean(),
              "Score within ±2.0": (err_m <= 2.0).mean(),
              "Severity off by ≥2 levels": (np.abs(test["severity"].map(SEVERITIES.index).values
                                                   - m["severity"].map(SEVERITIES.index).values) >= 2).mean()}
    out["score_tolerance"] = {k: float(v) for k, v in within.items()}
    report += [f"Score tolerance for {args.model}: " + ", ".join(f"{k} **{v:.1%}**" for k, v in within.items()), ""]

    # 2. Severity confusion matrix
    cm = pd.crosstab(pd.Categorical(test["severity"], SEVERITIES), pd.Categorical(m["severity"], SEVERITIES),
                     rownames=["true"], colnames=["pred"], dropna=False, normalize="index")
    support = test["severity"].value_counts().reindex(SEVERITIES).fillna(0).astype(int)
    cm_df = cm.reset_index().rename(columns={"true": "True \\ Pred"})
    cm_df.insert(1, "N", support.values)
    out["severity_confusion"] = cm.round(4).to_dict()
    report += ["## 2. Severity confusion matrix (row-normalised)\n", md(cm_df), ""]

    # 3. Drift: accuracy by publication quarter
    q = test["published"].dt.to_period("Q").astype(str)
    drift = pd.DataFrame({"quarter": q, "exact_m": exact_m, "exact_b": exact_b, "sev_m": sev_m,
                          "primary": test["source"].values == "Primary"}).groupby("quarter").agg(
        N=("exact_m", "size"), **{"NVD-scored share": ("primary", "mean"), f"{args.model} exact": ("exact_m", "mean"),
                                  f"{args.baseline} exact": ("exact_b", "mean"), f"{args.model} sev. acc": ("sev_m", "mean")}
    ).reset_index().rename(columns={"quarter": "Quarter"})
    out["by_quarter"] = drift.to_dict(orient="records")
    report += ["## 3. Drift by publication quarter\n", md(drift), ""]

    # 4. Per-metric accuracy split by scorer
    rows = []
    for scorer in ["Primary", "Secondary"]:
        mask = test["source"].values == scorer
        rows.append({"Scorer": scorer, "N": int(mask.sum()),
                     **{k: float((test[k].values[mask] == m[k].values[mask]).mean()) for k in METRICS}})
    out["per_metric_acc_by_scorer"] = rows
    report += ["## 4. Per-metric accuracy by scoring source\n", md(pd.DataFrame(rows)), ""]

    # 5. Biggest scoring organisations (Secondary only; the scorer column is the CNA/ADP contact)
    sec = test["source"].values == "Secondary"
    cna = pd.DataFrame({"CNA": test["scorer"].values[sec], "exact": exact_m[sec], "sev": sev_m[sec],
                        "mae": err_m[sec]}).groupby("CNA").agg(
        N=("exact", "size"), Exact=("exact", "mean"), **{"Sev. acc": ("sev", "mean")}, MAE=("mae", "mean")
    ).sort_values("N", ascending=False).head(15).reset_index()
    out["top_cnas"] = cna.to_dict(orient="records")
    report += ["## 5. Largest non-NVD scorers (CNAs and ADPs, Secondary-scored CVEs only)\n", md(cna), ""]

    # 6. Triage: coverage at several targets, and the agreement signal
    order = np.argsort(-m["confidence"].values)
    cov = {f"{t:.0%}": coverage_at(sev_m[order], t) for t in (0.95, 0.90, 0.85, 0.80, 0.75)}
    agree = (m[METRICS].values == b[METRICS].values).all(axis=1)
    out["coverage_at_target"] = cov
    out["agreement"] = {"share": float(agree.mean()), "sev_acc_agree": float(sev_m[agree].mean()),
                        "sev_acc_disagree": float(sev_m[~agree].mean()),
                        "exact_agree": float(exact_m[agree].mean()), "exact_disagree": float(exact_m[~agree].mean())}
    deciles = pd.qcut(m["confidence"].rank(method="first"), 10, labels=False)
    dec = pd.DataFrame({"decile": deciles.values, "conf": m["confidence"].values, "exact": exact_m, "sev": sev_m}).groupby(
        "decile").agg(**{"Mean conf.": ("conf", "mean"), "Exact": ("exact", "mean"), "Sev. acc": ("sev", "mean")}
                      ).reset_index()
    dec["decile"] = dec["decile"].map(lambda d: f"{d + 1}" + (" (least sure)" if d == 0 else " (most sure)" if d == 9 else ""))
    dec = dec.rename(columns={"decile": "Confidence decile"})
    out["calibration_deciles"] = dec.to_dict(orient="records")
    a = out["agreement"]
    report += ["## 6. Triage\n",
               "Share of CVEs that can be auto-scored (most confident first) at a severity-accuracy target:\n",
               md(pd.DataFrame([{"Target sev. acc": k, "Auto-scored share": v} for k, v in cov.items()])), "",
               "Accuracy by confidence decile:\n", md(dec), "",
               f"When {args.model} and {args.baseline} predict the same full vector ({a['share']:.1%} of CVEs), "
               f"severity accuracy is {a['sev_acc_agree']:.1%} (exact {a['exact_agree']:.1%}); "
               f"when they disagree it is {a['sev_acc_disagree']:.1%} (exact {a['exact_disagree']:.1%}).", ""]

    # 7. Description length
    words = test["description"].str.split().str.len()
    bins = pd.cut(words, [0, 20, 40, 80, 160, 10_000], labels=["≤20", "21–40", "41–80", "81–160", ">160"])
    ln = pd.DataFrame({"Words": bins.values, "exact": exact_m, "sev": sev_m}).groupby("Words", observed=True).agg(
        N=("exact", "size"), Exact=("exact", "mean"), **{"Sev. acc": ("sev", "mean")}).reset_index()
    out["by_length"] = ln.astype({"Words": str}).to_dict(orient="records")
    report += ["## 7. By description length (words)\n", md(ln), ""]

    # 8. Some descriptions (mostly Oracle's) spell out the vector itself; drop them to see the honest numbers
    leak = test["description"].str.contains(r"CVSS:3\.1/AV:|CVSS 3\.\d Base Score", regex=True).values
    rows = [{"System": name, "Exact (all)": e.mean(), "Exact (no vector in text)": e[~leak].mean(),
             "Sev. acc (all)": s.mean(), "Sev. acc (no vector in text)": s[~leak].mean()}
            for name, e, s in [(args.model, exact_m, sev_m), (args.baseline, exact_b, sev_b)]]
    out["vector_in_description"] = {"share": float(leak.mean()), "rows": rows}
    report += [f"## 8. Descriptions that contain the vector\n",
               f"{leak.mean():.1%} of test descriptions ({int(leak.sum()):,}) quote a CVSS 3.x score or vector "
               "(mostly Oracle). Results without them:\n", md(pd.DataFrame(rows)), ""]

    (args.results / "analysis.md").write_text("\n".join(report))
    (args.results / "analysis.json").write_text(json.dumps(out, indent=2, default=float))
    print("\n".join(report))


if __name__ == "__main__":
    main()
