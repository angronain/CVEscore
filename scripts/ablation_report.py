#!/usr/bin/env python3
"""v2 label-harmonisation ablation: corrector vs copy/lookup, then the 4 training variants.

Usage:
    python scripts/ablation_report.py

Reads:  data/processed/{train,test}.parquet, data/variants/corrector/test.parquet,
        results/preds_{deberta,corrector,v2_*}.parquet, results/v2/preds_tfidf.parquet
Writes: results/ablation.md, results/ablation.json
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from baselines import METRICS, add_scores  # noqa: E402

# (label, preds file relative to results/, prompt shown in the table)
SYSTEMS = [
    ("TF-IDF + LogReg", "v2/preds_tfidf.parquet", "–"),
    ("v1 (raw descriptions)", "preds_deberta.parquet", "–"),
    ("v2 base", "preds_v2_base.parquet", "–"),
    ("+ scorer tokens", "preds_v2_tokens_nvd.parquet", "[NVD]"),
    ("+ scorer tokens", "preds_v2_tokens.parquet", "matched"),
    ("+ label correction", "preds_v2_corrected.parquet", "–"),
    ("+ both", "preds_v2_both_nvd.parquet", "[NVD]"),
    ("+ both", "preds_v2_both.parquet", "matched"),
]


def split(vectors: pd.Series) -> pd.DataFrame:
    return pd.DataFrame([dict(p.split(":") for p in v.split("/")[1:]) for v in vectors], index=vectors.index)[METRICS]


def lookup_corrector(fit: pd.DataFrame, apply: pd.DataFrame, min_count: int = 20) -> pd.DataFrame:
    """Most frequent NVD value per (scorer, CNA value), backing off to the global mapping."""
    fc, fn, ac = split(fit["cna_vector"]), split(fit["nvd_vector"]), split(apply["cna_vector"])
    out = ac.copy()
    for k in METRICS:
        g = pd.DataFrame({"s": fit["cna_scorer"].values, "c": fc[k].values, "n": fn[k].values})
        mode = lambda x: x.value_counts().idxmax()
        by_s, cnt = g.groupby(["s", "c"])["n"].agg(mode).to_dict(), g.groupby(["s", "c"]).size().to_dict()
        glob = g.groupby("c")["n"].agg(mode).to_dict()
        out[k] = [by_s[(s, v)] if cnt.get((s, v), 0) >= min_count else glob.get(v, v)
                  for s, v in zip(apply["cna_scorer"].values, ac[k].values)]
    return out


def scores(t: pd.DataFrame, p: pd.DataFrame) -> dict:
    return {"exact": float((t[METRICS].values == p[METRICS].values).all(1).mean()),
            "sev": float((t["severity"].values == p["severity"].values).mean()),
            "mae": float(np.abs(t["score"].values - p["score"].values).mean())}


def bootstrap(a: np.ndarray, b: np.ndarray, n: int = 1000, seed: int = 0) -> tuple[float, float, float]:
    rng = np.random.default_rng(seed)
    d = a.astype(float) - b.astype(float)
    boots = np.array([d[rng.integers(0, len(d), len(d))].mean() for _ in range(n)])
    return float(d.mean()), float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))


def md(df: pd.DataFrame, fmt: str = "{:.3f}") -> str:
    f = lambda v: fmt.format(v) if isinstance(v, (float, np.floating)) else str(v)
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    return "\n".join(lines + ["| " + " | ".join(f(v) for v in r) + " |" for r in df.itertuples(index=False)])


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", type=Path, default=Path("data/processed"))
    p.add_argument("--variants", type=Path, default=Path("data/variants"))
    p.add_argument("--results", type=Path, default=Path("results"))
    args = p.parse_args()
    out, report = {}, ["# CVEscore v2: label-harmonisation ablation\n",
                       "Same time split as v1 (train < 2025, validation Oct–Dec 2024, test 2025+). "
                       "CVSS scores and vectors quoted in descriptions are stripped for every v2 system. "
                       "Generated by `scripts/ablation_report.py`.\n"]

    # ---- 1. Corrector: CNA vector -> NVD vector on the 2025+ CVEs scored by both ----
    train, test = pd.read_parquet(args.data / "train.parquet"), pd.read_parquet(args.data / "test.parquet")
    pairs = lambda d: d[d["nvd_vector"].notna() & d["cna_vector"].notna()]
    fit, tp = pairs(train), pairs(test).set_index("id")
    truth = split(tp["nvd_vector"])
    methods = {"Copy the CNA vector": split(tp["cna_vector"]),
               "Lookup table (scorer × value)": lookup_corrector(fit, tp.reset_index()).set_index(tp.index)}
    cf = args.results / "preds_corrector.parquet"
    if cf.exists():
        methods["DeBERTa corrector (ours)"] = pd.read_parquet(cf).set_index("id").loc[tp.index, METRICS]
    rows = []
    for name, pr in methods.items():
        r = {"Method": name, "Exact": float((pr.values == truth.values).all(1).mean())}
        r.update({k: float((pr[k].values == truth[k].values).mean()) for k in METRICS})
        rows.append(r)
    out["corrector"] = rows
    report += [f"## 1. Label corrector: predict NVD's vector from the CNA's ({len(tp):,} test CVEs scored by both)\n",
               "Input: CNA identity + CNA vector + description. Trained on pre-2025 pairs only. Per-metric accuracy:\n",
               md(pd.DataFrame(rows)), ""]

    # ---- 2. Ablation on the main task ----
    test = add_scores(test).set_index("id")
    subsets = {"NVD-scored": test["source"].values == "Primary", "CNA-scored": test["source"].values == "Secondary",
               "All": np.ones(len(test), bool)}
    preds, rows = {}, []
    for label, f, prompt in SYSTEMS:
        path = args.results / f
        if not path.exists():
            continue
        pr = pd.read_parquet(path).set_index("id")
        ids = test.index.intersection(pr.index)
        pr, t = pr.loc[ids], test.loc[ids]
        preds[(label, prompt)] = pr.reindex(test.index)
        r = {"System": label, "Prompt": prompt}
        for s, mask in subsets.items():
            m = pd.Series(mask, index=test.index).loc[ids].values
            sc = scores(t[m], pr[m])
            r.update({f"{s} exact": sc["exact"], f"{s} sev": sc["sev"], f"{s} MAE": sc["mae"]})
        rows.append(r)
    out["ablation"] = rows
    n = {s: int(m.sum()) for s, m in subsets.items()}
    report += ["## 2. Ablation\n",
               f"NVD-scored = {n['NVD-scored']:,} test CVEs scored by NVD (the target the harmonisation aims at). "
               f"CNA-scored = {n['CNA-scored']:,} scored only by the CNA/ADP. "
               "Prompt `[NVD]` asks every CVE for NVD's style; `matched` uses the tag of whoever scored the test "
               "label (known at publication).\n",
               md(pd.DataFrame(rows)), ""]

    # ---- 3. Is each gain real? Paired bootstrap vs v2 base ----
    base = preds.get(("v2 base", "–"))
    if base is not None:
        rows = []
        for (label, prompt), pr in preds.items():
            if label == "v2 base" or pr[METRICS].isna().any().any():
                continue
            for s in ["NVD-scored", "CNA-scored"]:
                m = subsets[s]
                t = test[m]
                a = (t[METRICS].values == pr[m][METRICS].values).all(1)
                b = (t[METRICS].values == base[m][METRICS].values).all(1)
                d, lo, hi = bootstrap(a, b)
                rows.append({"System": label, "Prompt": prompt, "Subset": s, "Δ exact vs base": d,
                             "95% CI low": lo, "95% CI high": hi})
        out["bootstrap_vs_base"] = rows
        report += ["## 3. Exact-vector gain over v2 base (paired bootstrap, 1,000 resamples)\n",
                   md(pd.DataFrame(rows), "{:+.4f}"), ""]

    (args.results / "ablation.md").write_text("\n".join(report))
    (args.results / "ablation.json").write_text(json.dumps(out, indent=2))
    print("\n".join(report))


if __name__ == "__main__":
    main()
